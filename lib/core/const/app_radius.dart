/// Corner radius scale.
class AppRadius {
  AppRadius._();

  /// 8px — standard buttons.
  static const double button = 8;

  /// 8px — input fields.
  static const double input = 8;

  /// 16px — cards.
  static const double card = 16;

  /// 16px — modals, dialogs, bottom sheets.
  static const double modal = 16;

  /// 4px — status badges / chips.
  static const double badge = 4;

  /// 4px — filter chips / small tags.
  static const double chip = 4;

  /// Full pill — avatars, circular buttons, FABs.
  static const double pill = 9999;
}